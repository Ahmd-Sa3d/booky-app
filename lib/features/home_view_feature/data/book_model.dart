class BookModel {
  final String title;
  final String subTitle;
  final String author;
  final String image;
  final double price;
  final double rating;
  final int views;

  BookModel({
    required this.title,
    required this.subTitle,
    required this.author,
    required this.image,
    required this.price,
    required this.rating,
    required this.views,
  });
}
